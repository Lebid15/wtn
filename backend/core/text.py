"""تنقية النصوص التي تُطابَق حرفاً بحرف."""

import unicodedata


def clean_login_id(raw) -> str:
    """
    رقم الدخول يُطابَق حرفاً بحرف، فحرفٌ لا يُرى يُفشل الدخول برسالة «بيانات
    الدخول غير صحيحة» — ولا شيء على الشاشة يفسّرها. الحقل يبدو مطابقاً تماماً،
    والدخول يُرفض أبداً.

    **وقد وقع فعلاً (2026-08-23):** نُسخ رقم صاحب متجر «zad» من عرضٍ عربي،
    فجاء معه محرفا العزل `U+2066` و`U+2069` حول الرقم وحُفظا في القاعدة.
    فصار `login_id` اثني عشر محرفاً لا عشرة، ولا يُطابقه ما يُكتب بيد.

    و`strip()` وحدها لا تمسكها: هي مسافةٌ في نظر العين لا في نظر بايثون.
    فتُحذف كل محارف الفئة `Cf` (العزل والتوجيه وعلامة الترتيب) مع كل مسافة —
    داخل النصّ لا في طرفيه فقط، إذ لا رقم دخولٍ فيه مسافةٌ مقصودة.
    """
    if not raw:
        return ""
    return "".join(
        ch for ch in str(raw)
        if unicodedata.category(ch) != "Cf" and not ch.isspace()
    )
